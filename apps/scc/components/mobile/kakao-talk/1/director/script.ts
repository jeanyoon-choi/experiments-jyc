const VOICE_REGISTERS: Record<Voice, readonly Register[]> = {
  young: ["casual"],
  parent: ["casual", "polite"],
  office: ["polite"],
  elder: ["elder", "elder", "casual"],
  anon: ["open", "polite", "casual"],
};

const assemble = (bank: Bank): Record<Voice, Tiers<string>> => {
  const tiers = (voice: Voice) => [0, 1, 2].map((tier) => VOICE_REGISTERS[voice].flatMap((register) => bank[register][tier])) as unknown as Tiers<string>;
  return { young: tiers("young"), parent: tiers("parent"), office: tiers("office"), elder: tiers("elder"), anon: tiers("anon") };
};

